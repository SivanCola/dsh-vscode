export type Locale = 'en' | 'zh-CN'
export type Language = 'auto' | Locale
export const isLanguage = (value: unknown): value is Language => value === 'auto' || value === 'en' || value === 'zh-CN'
export function resolveLocale(language: Language, editorLanguage: string): Locale {
  if (language !== 'auto') return language
  return editorLanguage.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}
export let uiStrings = en
export function useLocale(locale: Locale) { uiStrings = locale === 'en' ? en : zh }
